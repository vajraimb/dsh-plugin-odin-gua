#!/usr/bin/env node
// Generate lib/texts.generated.js from data/zhouyi.txt + data/legge.txt.
//
// Port of odin-gua's tools/gen_texts.py: the parser, the slot mapping and the
// cross-checks (中文“九/六”与卦画一致、英文 undivided/divided 与卦画一致) are
// kept, but the output is a JavaScript table instead of an Odin offset table.
//
// Usage: node tools/gen-texts.mjs

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')

// Same table as lib/tables.js KW (kept local so the generator has no import cycle).
const KW = [
  [2, 16, 8, 45, 23, 35, 20, 12],
  [24, 51, 3, 17, 27, 21, 42, 25],
  [7, 40, 29, 47, 4, 64, 59, 6],
  [19, 54, 60, 58, 41, 38, 61, 10],
  [15, 62, 39, 31, 52, 56, 53, 33],
  [36, 55, 63, 49, 22, 30, 37, 13],
  [46, 32, 48, 28, 18, 50, 57, 44],
  [11, 34, 5, 43, 26, 14, 9, 1],
]
const BITS = {}
for (let l = 0; l < 8; l += 1) for (let u = 0; u < 8; u += 1) BITS[KW[l][u]] = l | (u << 3)
const POS = ['初', '二', '三', '四', '五', '上']

function fnv1a64(buffer) {
  let h = 0xcbf29ce484222325n
  const prime = 0x100000001b3n
  for (const byte of buffer) {
    h ^= BigInt(byte)
    h = (h * prime) & 0xffffffffffffffffn
  }
  return h
}

function parse(data, tags) {
  const hdr = new Map()
  const span = new Map()
  for (const raw of data.split('\n')) {
    if (raw === '') continue
    const m = /^(\d\d) (.+)$/.exec(raw)
    if (m && Number(m[1]) === hdr.size + 1 && (hdr.size === 0 || span.get(hdr.size).size >= 7)) {
      const n = Number(m[1])
      hdr.set(n, m[2])
      span.set(n, new Map())
      continue
    }
    const cut = raw.indexOf(' ')
    if (cut < 0) throw new Error(`bad line: ${JSON.stringify(raw)}`)
    const tag = raw.slice(0, cut)
    const text = raw.slice(cut + 1)
    const n = hdr.size
    const slot = tags(n, tag)
    const slots = span.get(n)
    if (slot === null || slot === undefined) throw new Error(`unknown tag ${tag} in hexagram ${n}`)
    if (slots.has(slot)) throw new Error(`duplicate slot ${slot} in hexagram ${n}`)
    slots.set(slot, { text, tag })
  }
  return { hdr, span }
}

const zhTag = (_n, tag) => {
  if (tag === '卦辭') return 0
  if (tag === '用九' || tag === '用六') return 7
  for (let i = 0; i < POS.length; i += 1) {
    const pos = POS[i]
    if ((i === 0 || i === 5) && tag[0] === pos && '九六'.includes(tag[1])) return i + 1
    if (i !== 0 && i !== 5 && tag[1] === pos && '九六'.includes(tag[0])) return i + 1
  }
  return null
}

const enTag = (_n, tag) => {
  if (tag === 'J') return 0
  if (tag === 'U') return 7
  return '123456'.includes(tag) && tag.length === 1 ? Number(tag) : null
}

const zhBuf = readFileSync(join(ROOT, 'data/zhouyi.txt'))
const enBuf = readFileSync(join(ROOT, 'data/legge.txt'))
const zh = zhBuf.toString('utf8')
const en = enBuf.toString('utf8')
const zhParsed = parse(zh, zhTag)
const enParsed = parse(en, enTag)

// Same pre-flight checks gen_texts.py runs before writing the file.
const problems = []
const names = [...zhParsed.hdr.keys()].sort((a, b) => a - b)
if (names.length !== 64 || names[0] !== 1 || names[63] !== 64) problems.push(`expected 64 hexagrams, got ${names.length}`)
for (let n = 1; n <= 64; n += 1) {
  const want = new Set(Array.from({ length: n <= 2 ? 8 : 7 }, (_, i) => i))
  const got = new Set(zhParsed.span.get(n).keys())
  if (want.size !== got.size || [...want].some((s) => !got.has(s))) problems.push(`hexagram ${n} zh slots ${[...got]}`)
  for (let s = 1; s <= 6; s += 1) {
    const yang = ((BITS[n] >> (s - 1)) & 1) === 1
    const tag = zhParsed.span.get(n).get(s).tag
    const numer = s === 1 || s === 6 ? tag[1] : tag[0]
    if (numer !== (yang ? '九' : '六')) problems.push(`zh ${n}.${s}: ${tag} vs yang=${yang}`)
    const enText = enParsed.span.get(n).get(s).text
    const m = /\b(un)?divided\b/.exec(enText)
    if (!m) problems.push(`en ${n}.${s}: no divided/undivided`)
    else if (Boolean(m[1]) !== yang) problems.push(`en ${n}.${s}: ${m[0]} vs yang=${yang}`)
  }
}
if (problems.length) {
  console.error(problems.slice(0, 20).join('\n'))
  process.exit(1)
}

const q = (s) => JSON.stringify(s)
const table = (parsed, label) => {
  const rows = []
  for (let n = 1; n <= 64; n += 1) {
    const slots = parsed.span.get(n)
    const cells = []
    for (let s = 0; s < 8; s += 1) cells.push(slots.has(s) ? q(slots.get(s).text) : 'null')
    rows.push(`  [${cells.join(', ')}], // ${n} ${parsed.hdr.get(n)}`)
  }
  return `export const ${label} = [\n  null,\n${rows.join('\n')}\n]\n`
}

const out = `// GENERATED by tools/gen-texts.mjs from data/zhouyi.txt and data/legge.txt.
// Do not edit by hand: change the data files and re-run \`node tools/gen-texts.mjs\`.
//
// TEXTS_*[卦][槽]：槽 0 卦辞，1–6 初爻到上爻，7 用九/用六（仅乾坤）。
// 中文为通行本（繁体），英文为 Legge 1882。来源与逐条出处见 upstream data/SOURCES.md。

export const TEXTS_ID = ${q(`zh:${fnv1a64(zhBuf).toString(16).padStart(16, '0')} en:${fnv1a64(enBuf).toString(16).padStart(16, '0')}`)}

/** 繁体卦名（与经文同字形）。 */
export const NAME_TRAD = [
  '',
${names.map((n) => `  ${q(zhParsed.hdr.get(n))},`).join('\n')}
]

/** Legge 1882 原书拼写。 */
export const NAME_LEGGE = [
  '',
${names.map((n) => `  ${q(enParsed.hdr.get(n))},`).join('\n')}
]

${table(zhParsed, 'TEXTS_ZH')}
${table(enParsed, 'TEXTS_EN')}`

writeFileSync(join(ROOT, 'lib/texts.generated.js'), out)
console.log(
  `wrote lib/texts.generated.js  zh ${zhBuf.length} B  en ${enBuf.length} B  ` +
    `fnv64a zh=${fnv1a64(zhBuf).toString(16)} en=${fnv1a64(enBuf).toString(16)}`,
)
